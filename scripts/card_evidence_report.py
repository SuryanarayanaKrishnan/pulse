#!/usr/bin/env python3
"""Write docs/CARD_EVIDENCE.md: how well each card in the catalog is backed by an official source.

Tiers (best first):
  A  confidence high: cross-checked against an official bank page, KFS or T&C
  B  official source listed but not cross-checked (medium) or only partly read
  C  comparison site only
  D  low confidence or status unverified: do not state figures as fact

Run after any catalog change: python scripts/card_evidence_report.py  (tests fail if it is stale).
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OFFICIAL = {"bank_page", "kfs", "tc_pdf"}
OUT = ROOT / "docs" / "CARD_EVIDENCE.md"


def tier(c: dict) -> str:
    official = any(s["kind"] in OFFICIAL for s in c["sources"])
    if c["confidence"] == "low" or c["status"] == "unverified":
        return "D"
    if c["confidence"] == "high" and official:
        return "A"
    return "B" if official else "C"


def render() -> str:
    cards = json.loads((ROOT / "data/cards/catalog.json").read_text())["cards"]
    counts = Counter(tier(c) for c in cards)
    lines = [
        "# Card evidence report",
        "",
        "Generated by `scripts/card_evidence_report.py`. Do not edit by hand.",
        "",
        f"{len(cards)} cards. A (cross-checked on an official page): {counts['A']}. "
        f"B (official source listed, not cross-checked): {counts['B']}. "
        f"C (comparison site only): {counts['C']}. D (low confidence, do not state as fact): {counts['D']}.",
        "",
        "| Tier | Card | Issuer | Latest official check | Fields flagged | Sources |",
        "|---|---|---|---|---|---|",
    ]
    for c in sorted(cards, key=lambda c: (tier(c), c["issuer"], c["id"])):
        off = [s["verified_on"] for s in c["sources"] if s["kind"] in OFFICIAL]
        flagged = ", ".join(sorted(c.get("field_confidence", {}))) or ""
        kinds = ", ".join(sorted({s["kind"] for s in c["sources"]}))
        lines.append(
            f"| {tier(c)} | {c['id']} | {c['issuer']} | {max(off) if off else 'never'} | {flagged} | {kinds} |"
        )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(render())
    print(f"wrote {OUT}")
